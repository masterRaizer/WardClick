CREATE TABLE dbo.Cities (
    id   INT IDENTITY(1,1) CONSTRAINT PK_Cities PRIMARY KEY,
    name NVARCHAR(60) NOT NULL CONSTRAINT UQ_Cities_name UNIQUE
);
CREATE TABLE dbo.PropertyTypes (
    id   INT IDENTITY(1,1) CONSTRAINT PK_PropertyTypes PRIMARY KEY,
    name NVARCHAR(40) NOT NULL,
    code NVARCHAR(20) NOT NULL CONSTRAINT UQ_PropertyTypes_code UNIQUE
);
CREATE TABLE dbo.Amenities (
    id        INT IDENTITY(1,1) CONSTRAINT PK_Amenities PRIMARY KEY,
    name      NVARCHAR(60) NOT NULL,
    icon_code NVARCHAR(30) NOT NULL
);
CREATE TABLE dbo.Users (
    id            INT IDENTITY(1,1) CONSTRAINT PK_Users PRIMARY KEY,
    full_name     NVARCHAR(100) NOT NULL,
    email         NVARCHAR(100) NOT NULL CONSTRAINT UQ_Users_email UNIQUE,
    password_hash NVARCHAR(255) NOT NULL,
    phone         NVARCHAR(20) NULL,
    role          NVARCHAR(10) NOT NULL CONSTRAINT DF_Users_role DEFAULT N'USER'
                  CONSTRAINT CK_Users_role CHECK (role IN (N'USER', N'ADMIN')),
    is_superhost  BIT NOT NULL CONSTRAINT DF_Users_superhost DEFAULT 0,
    created_at    DATETIME2 NOT NULL CONSTRAINT DF_Users_created DEFAULT SYSDATETIME()
);
CREATE TABLE dbo.Listings (
    id               INT IDENTITY(1,1) CONSTRAINT PK_Listings PRIMARY KEY,
    title            NVARCHAR(150) NOT NULL,
    description      NVARCHAR(MAX) NULL,
    city_id          INT NOT NULL CONSTRAINT FK_Listings_Cities REFERENCES dbo.Cities(id),
    property_type_id INT NOT NULL CONSTRAINT FK_Listings_PropertyTypes REFERENCES dbo.PropertyTypes(id),
    host_id          INT NOT NULL CONSTRAINT FK_Listings_Users REFERENCES dbo.Users(id),
    address          NVARCHAR(200) NOT NULL,
    price_per_night  DECIMAL(12,2) NOT NULL CONSTRAINT CK_Listings_price CHECK (price_per_night > 0),
    vip_factor       DECIMAL(4,2) NOT NULL CONSTRAINT DF_Listings_vip DEFAULT 1.00,
    max_guests       INT NOT NULL CONSTRAINT CK_Listings_guests CHECK (max_guests > 0),
    bedrooms         INT NOT NULL,
    beds             INT NOT NULL,
    bathrooms        INT NOT NULL,
    latitude         FLOAT NOT NULL,
    longitude        FLOAT NOT NULL,
    rating           DECIMAL(2,1) NOT NULL CONSTRAINT DF_Listings_rating DEFAULT 0,
    reviews_count    INT NOT NULL CONSTRAINT DF_Listings_reviews DEFAULT 0,
    is_active        BIT NOT NULL CONSTRAINT DF_Listings_active DEFAULT 1
);
CREATE TABLE dbo.ListingPhotos (
    id         INT IDENTITY(1,1) CONSTRAINT PK_ListingPhotos PRIMARY KEY,
    listing_id INT NOT NULL CONSTRAINT FK_ListingPhotos_Listings REFERENCES dbo.Listings(id) ON DELETE CASCADE,
    url        NVARCHAR(300) NOT NULL,
    sort_order INT NOT NULL CONSTRAINT DF_ListingPhotos_sort DEFAULT 0
);
CREATE TABLE dbo.ListingAmenities (
    listing_id INT NOT NULL CONSTRAINT FK_ListingAmenities_Listings REFERENCES dbo.Listings(id) ON DELETE CASCADE,
    amenity_id INT NOT NULL CONSTRAINT FK_ListingAmenities_Amenities REFERENCES dbo.Amenities(id),
    CONSTRAINT PK_ListingAmenities PRIMARY KEY (listing_id, amenity_id)
);
CREATE TABLE dbo.Favorites (
    user_id    INT NOT NULL CONSTRAINT FK_Favorites_Users REFERENCES dbo.Users(id),
    listing_id INT NOT NULL CONSTRAINT FK_Favorites_Listings REFERENCES dbo.Listings(id),
    added_at   DATETIME2 NOT NULL CONSTRAINT DF_Favorites_added DEFAULT SYSDATETIME(),
    CONSTRAINT PK_Favorites PRIMARY KEY (user_id, listing_id)
);
CREATE TABLE dbo.Orders (
    id         INT IDENTITY(1,1) CONSTRAINT PK_Orders PRIMARY KEY,
    user_id    INT NOT NULL CONSTRAINT FK_Orders_Users REFERENCES dbo.Users(id),
    discount   DECIMAL(12,2) NOT NULL CONSTRAINT DF_Orders_discount DEFAULT 0,
    total      DECIMAL(12,2) NOT NULL,
    created_at DATETIME2 NOT NULL CONSTRAINT DF_Orders_created DEFAULT SYSDATETIME()
);
CREATE TABLE dbo.Bookings (
    id            INT IDENTITY(1,1) CONSTRAINT PK_Bookings PRIMARY KEY,
    listing_id    INT NOT NULL CONSTRAINT FK_Bookings_Listings REFERENCES dbo.Listings(id),
    user_id       INT NOT NULL CONSTRAINT FK_Bookings_Users REFERENCES dbo.Users(id),
    order_id      INT NULL CONSTRAINT FK_Bookings_Orders REFERENCES dbo.Orders(id),
    check_in      DATE NOT NULL,
    check_out     DATE NOT NULL,
    guests_count  INT NOT NULL CONSTRAINT CK_Bookings_guests CHECK (guests_count > 0),
    vip_total     DECIMAL(12,2) NOT NULL CONSTRAINT DF_Bookings_vip DEFAULT 0,
    discount      DECIMAL(12,2) NOT NULL CONSTRAINT DF_Bookings_discount DEFAULT 0,
    total_price   DECIMAL(12,2) NOT NULL,
    all_inclusive BIT NOT NULL CONSTRAINT DF_Bookings_all DEFAULT 0,
    status        NVARCHAR(12) NOT NULL CONSTRAINT DF_Bookings_status DEFAULT N'PENDING'
                  CONSTRAINT CK_Bookings_status CHECK (status IN (N'PENDING', N'CONFIRMED', N'CANCELLED')),
    created_at    DATETIME2 NOT NULL CONSTRAINT DF_Bookings_created DEFAULT SYSDATETIME(),
    CONSTRAINT CK_Bookings_dates CHECK (check_out > check_in AND DATEDIFF(DAY, check_in, check_out) <= 30)
);
CREATE TABLE dbo.VipServices (
    id               INT IDENTITY(1,1) CONSTRAINT PK_VipServices PRIMARY KEY,
    name             NVARCHAR(80) NOT NULL,
    description      NVARCHAR(400) NULL,
    icon_code        NVARCHAR(30) NOT NULL,
    base_price       DECIMAL(12,2) NOT NULL,
    unit             NVARCHAR(10) NOT NULL CONSTRAINT CK_VipServices_unit CHECK (unit IN (N'PER_DAY', N'PER_TRIP', N'ONCE')),
    requires_helipad BIT NOT NULL CONSTRAINT DF_VipServices_heli DEFAULT 0
);
CREATE TABLE dbo.BookingVipServices (
    booking_id     INT NOT NULL CONSTRAINT FK_BookingVip_Bookings REFERENCES dbo.Bookings(id) ON DELETE CASCADE,
    vip_service_id INT NOT NULL CONSTRAINT FK_BookingVip_VipServices REFERENCES dbo.VipServices(id),
    price          DECIMAL(12,2) NOT NULL,
    CONSTRAINT PK_BookingVipServices PRIMARY KEY (booking_id, vip_service_id)
);
CREATE TABLE dbo.Reviews (
    id         INT IDENTITY(1,1) CONSTRAINT PK_Reviews PRIMARY KEY,
    booking_id INT NOT NULL CONSTRAINT FK_Reviews_Bookings REFERENCES dbo.Bookings(id)
               CONSTRAINT UQ_Reviews_booking UNIQUE,
    listing_id INT NOT NULL CONSTRAINT FK_Reviews_Listings REFERENCES dbo.Listings(id),
    user_id    INT NOT NULL CONSTRAINT FK_Reviews_Users REFERENCES dbo.Users(id),
    rating     TINYINT NOT NULL CONSTRAINT CK_Reviews_rating CHECK (rating BETWEEN 1 AND 5),
    comment    NVARCHAR(1000) NULL,
    created_at DATE NOT NULL
);
CREATE INDEX IX_Bookings_listing_dates ON dbo.Bookings (listing_id, check_in, check_out);
CREATE INDEX IX_Listings_city ON dbo.Listings (city_id);
CREATE INDEX IX_Reviews_listing ON dbo.Reviews (listing_id);
GO

